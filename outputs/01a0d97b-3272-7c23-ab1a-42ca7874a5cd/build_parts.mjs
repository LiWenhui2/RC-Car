import fs from 'node:fs/promises';
import path from 'node:path';
import { Workbook, SpreadsheetFile } from '@oai/artifact-tool';

const source = 'H:/RC-Car/AD/Documentation/RC-Car-V1_车辆端元器件主数据表.md';
const outputDir = 'H:/RC-Car/outputs/01a0d97b-3272-7c23-ab1a-42ca7874a5cd';
const lines = (await fs.readFile(source, 'utf8')).trim().split(/\r?\n/);
const parse = line => line.slice(1, -1).split('|').map(x => x.trim());
const headers = parse(lines[0]);
const rows = lines.slice(2).map(parse);
if (headers.length !== 13 || rows.length !== 37 || rows.some(r => r.length !== 13)) throw new Error('Source table dimensions unexpected');
const data = [headers, ...rows.map(r => r.map((v, i) => i === 10 && /^\d+$/.test(v) ? Number(v) : v))];
const workbook = Workbook.create();
const sheet = workbook.worksheets.add('元器件主数据');
sheet.showGridLines = false;
sheet.getRange('A1:M38').values = data;
sheet.getRange('A1:M38').format.font = { name: 'Arial', size: 10, color: '#172033' };
sheet.getRange('A1:M1').format = { fill: '#17365D', font: { name: 'Arial', size: 10, bold: true, color: '#FFFFFF' }, rowHeight: 30, horizontalAlignment: 'center', verticalAlignment: 'center' };
sheet.getRange('A2:M38').format.rowHeight = 23;
sheet.getRange('A2:M38').format.verticalAlignment = 'center';
const widths = [34, 19, 24, 45, 53, 20, 27, 13, 23, 19, 11, 13, 72];
for (let i = 0; i < 13; i++) sheet.getRangeByIndexes(0, i, 38, 1).format.columnWidth = widths[i];
sheet.getRange('K2:K38').format.numberFormat = '#,##0';
sheet.freezePanes.freezeRows(1);
sheet.tables.add('A1:M38', true, 'PartsMaster');
workbook.recalculate();
const check = await workbook.inspect({kind:'table',range:'元器件主数据!A1:M4',include:'values',tableMaxRows:4,tableMaxCols:13});
console.log(check.ndjson);
const preview = await workbook.render({sheetName:'元器件主数据',range:'A1:F5',scale:1.5,format:'png'});
await fs.mkdir(outputDir, {recursive:true});
await fs.writeFile(path.join(outputDir,'preview.png'), new Uint8Array(await preview.arrayBuffer()));
const xlsx = await SpreadsheetFile.exportXlsx(workbook);
const out = path.join(outputDir,'RC-Car-V1_车辆端元器件主数据表.xlsx');
await xlsx.save(out);
console.log(JSON.stringify({out,headers:headers.length,rows:rows.length,bytes:(await fs.stat(out)).size}));
